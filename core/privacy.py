"""个人信息脱敏的唯一实现。

监管台账、宠物生命周期这类**批量/跨角色**读取接口，必须把「核身需要的
信息」与「可批量导出的信息」分开：列表一次下发整区县乃至全市的记录，
全号明文等于一份可导出、可检索的公民敏感信息集合。

保留前后若干位，足够人眼比对两张单据是否同人，又不至于被直接还原。
长度异常（历史脏数据、手填少位）一律整串打码，不做「看起来像号」的猜测。
"""


def mask_id_card(value):
    """身份证号：保留前 6（地址码）与后 4（顺序码+校验位），中间打码。"""
    s = (value or '').strip()
    if not s:
        return ''
    if len(s) in (15, 18):
        return s[:6] + '*' * (len(s) - 10) + s[-4:]
    return '*' * len(s)


def mask_phone(value):
    """电话号码：保留前 3 与后 4，中间打码。

    短于 8 位的号码（含历史脏数据里的 7 位座机）整串打码 ——
    按「前 3 + 后 4」去脱敏 7 位串等于原样返回。
    """
    s = (value or '').strip()
    if not s:
        return ''
    if len(s) >= 8:
        return s[:3] + '*' * (len(s) - 7) + s[-4:]
    return '*' * len(s)
